param(
    [Parameter(Mandatory = $true)][string]$ZigPath,
    [string]$OutputPath,
    [ValidatePattern('^\d{1,5}\.\d{1,5}\.\d{1,5}$')][string]$Version = '1.0.0'
)
$ErrorActionPreference = 'Stop'
if (!$OutputPath) { $OutputPath = Join-Path $PSScriptRoot 'DoWATT.exe' }
$ZigPath = (Resolve-Path -LiteralPath $ZigPath).Path
$zigRoot = Split-Path -Parent $ZigPath
$buildRoot = Join-Path $PSScriptRoot 'build'
New-Item -ItemType Directory -Force -Path $buildRoot | Out-Null
$sourceRoot = Join-Path $PSScriptRoot 'src'
$parts = $Version.Split('.') | ForEach-Object { [int]$_ }
foreach ($part in $parts) { if ($part -gt 65535) { throw 'Each version component must be <= 65535' } }
$numericVersion = ($parts -join ',') + ',0'
@"
// Generated by build.ps1. SPDX-License-Identifier: GPL-3.0-only
#define DoWATT_VERSION_W L"$Version"
#define DoWATT_VERSION_A "$Version"
#define DoWATT_VERSION_NUM $numericVersion
"@ | Set-Content -LiteralPath (Join-Path $buildRoot 'version.h') -Encoding ASCII
$manifest = (Get-Content -Raw -LiteralPath (Join-Path $sourceRoot 'DoWATT.manifest')).Replace('1.0.0.0', "$Version.0")
$manifest | Set-Content -LiteralPath (Join-Path $buildRoot 'DoWATT.manifest') -Encoding UTF8
Copy-Item -LiteralPath (Join-Path $sourceRoot 'DoWATT.rc') -Destination (Join-Path $buildRoot 'DoWATT.rc')
function Invoke-Zig([string[]]$Arguments) {
    & $ZigPath @Arguments
    if ($LASTEXITCODE -ne 0) { throw "Zig failed with exit code $LASTEXITCODE" }
}
# Generate import libraries from the compiler's Windows ABI definitions.
# They contain DLL symbol references, not bundled Windows/vendor implementations.
$libraries = @()
foreach ($name in @('kernel32', 'user32', 'gdi32', 'shell32', 'ole32', 'oleaut32', 'setupapi', 'advapi32')) {
    $definitions = Join-Path $zigRoot "lib\libc\mingw\lib-common\$name.def.in"
    if (!(Test-Path -LiteralPath $definitions)) {
        $definitions = Join-Path $zigRoot "lib\libc\mingw\lib-common\$name.def"
    }
    $processed = Join-Path $buildRoot "$name.def"
    $library = Join-Path $buildRoot "$name.lib"
    Invoke-Zig @('clang', '-E', '-P', '-x', 'c', '-target', 'x86_64-windows-gnu',
        '-nostdinc', '-isystem', (Join-Path $zigRoot 'lib\include'), '-isystem', (Join-Path $zigRoot 'lib\libc\include\any-windows-any'), '-resource-dir', (Join-Path $zigRoot 'lib'), '-I', (Join-Path $zigRoot 'lib\libc\mingw\def-include'), $definitions, '-o', $processed)
    Invoke-Zig @('dlltool', '-m', 'i386:x86-64', '-d', $processed, '-l', $library)
    $libraries += $library
}
$objects = @()
foreach ($name in @('DoWATT', 'estimate', 'cpu_power', 'graphics_inventory')) {
    $object = Join-Path $buildRoot "$name.obj"
    Invoke-Zig @('clang', '-c', (Join-Path $sourceRoot "$name.cpp"), '-o', $object,
        '-target', 'x86_64-windows-gnu', '-I', $buildRoot, '-nostdinc', '-isystem', (Join-Path $zigRoot 'lib\include'), '-isystem', (Join-Path $zigRoot 'lib\libc\include\any-windows-any'), '-resource-dir', (Join-Path $zigRoot 'lib'), '-Os', '-fno-exceptions', '-fno-rtti',
        '-fno-stack-protector', '-fno-builtin', '-Wall', '-Wextra', '-Werror')
    $objects += $object
}
$resource = Join-Path $buildRoot 'DoWATT.res'
if (-not ('DoWATTResources' -as [type])) { Add-Type -Path (Join-Path $sourceRoot 'resources.cs') }
[DoWATTResources]::Write($resource, (Join-Path $PSScriptRoot 'assets\DoWATT.ico'), (Join-Path $buildRoot 'DoWATT.manifest'), (Join-Path $sourceRoot 'DoWATT.rc'), $Version)
$linkArguments = @('lld-link') + $objects + @($resource) + $libraries + @(
    '/entry:entry', '/nodefaultlib', '/machine:x64', '/subsystem:windows',
    '/stack:1048576', '/opt:ref', '/opt:icf', '/dynamicbase', '/highentropyva', '/nxcompat', "/out:$OutputPath")
Invoke-Zig $linkArguments
Get-Item -LiteralPath $OutputPath | Select-Object Name, Length, @{Name='Version';Expression={$_.VersionInfo.FileVersion}}
